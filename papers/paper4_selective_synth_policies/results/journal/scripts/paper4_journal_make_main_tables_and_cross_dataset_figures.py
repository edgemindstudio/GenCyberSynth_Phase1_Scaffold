#!/usr/bin/env python3
from pathlib import Path
import pandas as pd
import matplotlib.pyplot as plt

ROOT = Path("papers/paper4_selective_synth_policies")
OUT_TABLE_DIR = ROOT / "results/journal/tables"
OUT_FIG_DIR = ROOT / "results/journal/figures"

OUT_TABLE_DIR.mkdir(parents=True, exist_ok=True)
OUT_FIG_DIR.mkdir(parents=True, exist_ok=True)

USTC_IN = ROOT / "results/tables/paper4_policy_mean_std.csv"
CIC_IN = ROOT / "results/journal/tables/paper4_journal_cicmaldroid_policy_mean_std.csv"

METRIC_LABELS = {
    "delta_macro_f1": "Delta Macro-F1",
    "delta_bal_acc": "Delta Bal. Acc.",
    "delta_macro_auprc": "Delta Macro-AUPRC",
    "delta_ece": "Delta ECE",
    "delta_brier": "Delta Brier",
}

USTC_POLICY_MAP = {
    "paper4_policy_keep_all_b2000": "Keep-all b2000",
    "paper4_policy_confidence_ranked_topk1000_b2000": "Top-k1000",
    "paper4_policy_class_repair_topk9000_b2000": "Class-repair",
    "paper4_policy_confidence_accept_t080_b2000": "Strict-conf.",
    "paper4_policy_confidence_ranked_topk500_b2000": "Top-k500",
}

USTC_ORDER = ["Keep-all b2000", "Strict-conf.", "Top-k500", "Top-k1000", "Class-repair"]

CIC_ORDER = ["CIC Keep-all b2000", "CIC Top-k1000", "CIC Class-repair"]

CROSS_POLICY_RENAME = {
    "Keep-all b2000": "Keep-all",
    "Top-k1000": "Top-k1000",
    "Class-repair": "Class-repair",
    "CIC Keep-all b2000": "Keep-all",
    "CIC Top-k1000": "Top-k1000",
    "CIC Class-repair": "Class-repair",
}

CROSS_ORDER = ["Keep-all", "Top-k1000", "Class-repair"]


def fmt_pm(mean, std):
    if pd.isna(mean):
        return ""
    if pd.isna(std):
        return f"{mean:.4f}"
    return f"{mean:.4f} $\\pm$ {std:.4f}"


def write_markdown(df: pd.DataFrame, path: Path):
    tmp = df.copy().astype("object").fillna("")
    headers = list(tmp.columns)
    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join(["---"] * len(headers)) + " |"]
    for _, row in tmp.iterrows():
        lines.append("| " + " | ".join(str(row[h]) for h in headers) + " |")
    path.write_text("\n".join(lines) + "\n")


def dataframe_to_latex_table(df: pd.DataFrame, caption: str, label: str) -> str:
    cols = list(df.columns)
    align = "l" + "r" * (len(cols) - 1)
    lines = []
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\caption{" + caption + "}")
    lines.append("\\label{" + label + "}")
    lines.append("\\resizebox{\\columnwidth}{!}{%")
    lines.append("\\begin{tabular}{" + align + "}")
    lines.append("\\toprule")
    lines.append(" & ".join(cols) + " \\\\")
    lines.append("\\midrule")
    for _, row in df.iterrows():
        vals = [str(row[c]) for c in cols]
        lines.append(" & ".join(vals) + " \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}%")
    lines.append("}")
    lines.append("\\end{table}")
    return "\n".join(lines) + "\n"


def make_ustc_table():
    df = pd.read_csv(USTC_IN)
    if "policy_label" not in df.columns:
        raise RuntimeError("Expected policy_label in USTC table")

    # Prefer the human-readable policy_label column already generated by the paper4 script.
    keep_labels = set(USTC_ORDER)
    sub = df[df["policy_label"].isin(keep_labels)].copy()

    if sub.empty:
        # Fallback to config_id map if labels differ.
        sub = df[df["config_id"].isin(USTC_POLICY_MAP)].copy()
        sub["policy_label"] = sub["config_id"].map(USTC_POLICY_MAP)

    sub["_order"] = sub["policy_label"].map({p: i for i, p in enumerate(USTC_ORDER)})
    sub = sub.sort_values("_order", kind="stable").drop(columns=["_order"])

    rows = []
    for _, r in sub.iterrows():
        policy = r["policy_label"]
        samples = r.get("num_fake_mean", r.get("mean_num_fake", ""))
        budget = r.get("budget_per_class", "")
        rows.append({
            "Policy": policy,
            "Samples": int(round(float(samples))) if pd.notna(samples) and str(samples) != "" else "",
            "Selected budget": budget,
            "$\\Delta$ Macro-F1": fmt_pm(r.get("delta_macro_f1_mean"), r.get("delta_macro_f1_std")),
            "$\\Delta$ Bal. Acc.": fmt_pm(r.get("delta_bal_acc_mean"), r.get("delta_bal_acc_std")),
            "$\\Delta$ Macro-AUPRC": fmt_pm(r.get("delta_macro_auprc_mean"), r.get("delta_macro_auprc_std")),
        })

    out = pd.DataFrame(rows)
    out_csv = OUT_TABLE_DIR / "paper4_main_table_ustc_policy_summary.csv"
    out_md = OUT_TABLE_DIR / "paper4_main_table_ustc_policy_summary.md"
    out_tex = OUT_TABLE_DIR / "paper4_main_table_ustc_policy_summary.tex"

    out.to_csv(out_csv, index=False)
    write_markdown(out, out_md)
    out_tex.write_text(dataframe_to_latex_table(out, "USTC-TFC2016 policy summary. Values report mean $\\pm$ standard deviation across seeds.", "tab:ustc_policy_summary"))

    return sub


def make_cic_table():
    df = pd.read_csv(CIC_IN)
    sub = df[df["policy_label"].isin(CIC_ORDER)].copy()
    sub["_order"] = sub["policy_label"].map({p: i for i, p in enumerate(CIC_ORDER)})
    sub = sub.sort_values("_order", kind="stable").drop(columns=["_order"])

    rows = []
    for _, r in sub.iterrows():
        rows.append({
            "Policy": r["policy_label"].replace("CIC ", ""),
            "Samples": int(round(float(r["mean_num_fake"]))),
            "$\\Delta$ Macro-F1": fmt_pm(r.get("delta_macro_f1_mean"), r.get("delta_macro_f1_std")),
            "$\\Delta$ Bal. Acc.": fmt_pm(r.get("delta_bal_acc_mean"), r.get("delta_bal_acc_std")),
            "$\\Delta$ Macro-AUPRC": fmt_pm(r.get("delta_macro_auprc_mean"), r.get("delta_macro_auprc_std")),
            "$\\Delta$ ECE": fmt_pm(r.get("delta_ece_mean"), r.get("delta_ece_std")),
            "$\\Delta$ Brier": fmt_pm(r.get("delta_brier_mean"), r.get("delta_brier_std")),
        })

    out = pd.DataFrame(rows)
    out_csv = OUT_TABLE_DIR / "paper4_main_table_cic_policy_summary.csv"
    out_md = OUT_TABLE_DIR / "paper4_main_table_cic_policy_summary.md"
    out_tex = OUT_TABLE_DIR / "paper4_main_table_cic_policy_summary.tex"

    out.to_csv(out_csv, index=False)
    write_markdown(out, out_md)
    out_tex.write_text(dataframe_to_latex_table(out, "CICMalDroid2020 policy summary. Values report mean $\\pm$ standard deviation across seeds.", "tab:cic_policy_summary"))

    return sub


def make_cross_dataset_figures(ustc_sub: pd.DataFrame, cic_sub: pd.DataFrame):
    ustc_cross = ustc_sub[ustc_sub["policy_label"].isin(["Keep-all b2000", "Top-k1000", "Class-repair"])].copy()
    ustc_cross["Dataset"] = "USTC-TFC2016"
    ustc_cross["Policy"] = ustc_cross["policy_label"].map(CROSS_POLICY_RENAME)

    cic_cross = cic_sub.copy()
    cic_cross["Dataset"] = "CICMalDroid2020"
    cic_cross["Policy"] = cic_cross["policy_label"].map(CROSS_POLICY_RENAME)

    combined_rows = []
    for _, r in ustc_cross.iterrows():
        combined_rows.append({
            "Dataset": r["Dataset"],
            "Policy": r["Policy"],
            "delta_macro_f1_mean": r["delta_macro_f1_mean"],
            "delta_bal_acc_mean": r["delta_bal_acc_mean"],
            "delta_macro_auprc_mean": r["delta_macro_auprc_mean"],
        })

    for _, r in cic_cross.iterrows():
        combined_rows.append({
            "Dataset": r["Dataset"],
            "Policy": r["Policy"],
            "delta_macro_f1_mean": r["delta_macro_f1_mean"],
            "delta_bal_acc_mean": r["delta_bal_acc_mean"],
            "delta_macro_auprc_mean": r["delta_macro_auprc_mean"],
        })

    cross = pd.DataFrame(combined_rows)
    cross["Policy"] = pd.Categorical(cross["Policy"], categories=CROSS_ORDER, ordered=True)
    cross = cross.sort_values(["Policy", "Dataset"], kind="stable")

    cross_csv = OUT_TABLE_DIR / "paper4_cross_dataset_policy_summary.csv"
    cross_md = OUT_TABLE_DIR / "paper4_cross_dataset_policy_summary.md"
    cross.to_csv(cross_csv, index=False)
    write_markdown(cross.round(6), cross_md)

    for metric, ylabel in [
        ("delta_macro_f1_mean", "Mean Delta Macro-F1"),
        ("delta_bal_acc_mean", "Mean Delta Balanced Accuracy"),
        ("delta_macro_auprc_mean", "Mean Delta Macro-AUPRC"),
    ]:
        fig, ax = plt.subplots(figsize=(7.2, 4.8))

        pivot = cross.pivot(index="Policy", columns="Dataset", values=metric).reindex(CROSS_ORDER)
        x = range(len(pivot.index))
        width = 0.35

        datasets = list(pivot.columns)
        for i, dataset in enumerate(datasets):
            offsets = [v + (i - 0.5) * width for v in x]
            ax.bar(offsets, pivot[dataset].values, width=width, label=dataset)

        ax.axhline(0, linewidth=1)
        ax.set_xticks(list(x))
        ax.set_xticklabels(list(pivot.index))
        ax.set_xlabel("Policy")
        ax.set_ylabel(ylabel)
        ax.set_title(ylabel + " across datasets")
        ax.legend()
        fig.tight_layout()

        stem = metric.replace("_mean", "")
        fig.savefig(OUT_FIG_DIR / f"paper4_cross_dataset_{stem}.png", dpi=300)
        fig.savefig(OUT_FIG_DIR / f"paper4_cross_dataset_{stem}.pdf")
        plt.close(fig)


def main():
    ustc_sub = make_ustc_table()
    cic_sub = make_cic_table()
    make_cross_dataset_figures(ustc_sub, cic_sub)

    print("[ok] wrote main USTC table files")
    print("[ok] wrote main CICMalDroid table files")
    print("[ok] wrote cross-dataset summary and figures")
    print("[ok] output tables:", OUT_TABLE_DIR)
    print("[ok] output figures:", OUT_FIG_DIR)


if __name__ == "__main__":
    main()